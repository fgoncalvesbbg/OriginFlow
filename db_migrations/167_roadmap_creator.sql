create policy "roadmap_axis_value_write" on public.roadmap_axis_value
  for all to authenticated
  using (public.is_roadmap_editor())
  with check (public.is_roadmap_editor());

drop policy if exists "roadmap_audit_read" on public.roadmap_audit;
create policy "roadmap_audit_read" on public.roadmap_audit
  for select to authenticated using (true);

-- Append-only in the strong sense: INSERT is allowed, UPDATE and DELETE have no policy, so the
-- log cannot be rewritten by anyone who reaches it through PostgREST.
drop policy if exists "roadmap_audit_append" on public.roadmap_audit;
create policy "roadmap_audit_append" on public.roadmap_audit
  for insert to authenticated
  with check (public.is_roadmap_editor());

-- Blanket table grants with RLS as the boundary, matching every other table in this schema.
-- Note roadmap_sku/roadmap_import get no insert/update/delete grant either: belt and braces
-- with the missing write policies above.
-- REVOKE FIRST — this is not belt-and-braces, it is a correction. Supabase ships
-- `alter default privileges in schema public grant all on tables to anon, authenticated`, so
-- every table created above arrives with INSERT/UPDATE/DELETE/TRUNCATE already granted to BOTH
-- roles. Verified live 2026-09-09: anon held all seven privileges on all six roadmap tables.
--
-- RLS still denied all of it — every policy here is `to authenticated`, and anon has no policy at
-- all, so with RLS enabled anon can do nothing. But that means ONE permissive `for all to public`
-- policy added later would silently hand anon write access to the whole module. Revoking makes
-- the grant layer agree with the policy layer instead of relying on it.
--
-- service_role is left alone deliberately: it bypasses RLS by design, is never reachable from a
-- browser, and every other table in this schema leaves it as Supabase set it.
revoke all on public.roadmap_import     from anon, authenticated;
revoke all on public.roadmap_sku        from anon, authenticated;
revoke all on public.roadmap_item_flag  from anon, authenticated;
revoke all on public.roadmap_placer     from anon, authenticated;
revoke all on public.roadmap_axis_value from anon, authenticated;
revoke all on public.roadmap_audit      from anon, authenticated;

-- Now the grants this module actually wants. The two reference tables get SELECT only: their
-- only writer is roadmap_import_skus(), which is SECURITY DEFINER and bypasses both layers.
grant select                         on public.roadmap_import     to authenticated;
grant select                         on public.roadmap_sku        to authenticated;
grant select, insert, update, delete on public.roadmap_item_flag  to authenticated;
grant select, insert, update, delete on public.roadmap_placer     to authenticated;
grant select, insert, update, delete on public.roadmap_axis_value to authenticated;
-- Append-only at the grant layer too: no update, no delete.
grant select, insert                 on public.roadmap_audit      to authenticated;

grant usage, select on sequence public.roadmap_placer_placer_id_seq     to authenticated;
grant usage, select on sequence public.roadmap_axis_value_axis_value_id_seq to authenticated;
grant usage, select on sequence public.roadmap_audit_audit_id_seq       to authenticated;

grant execute on function public.is_roadmap_editor()                      to authenticated;
grant execute on function public.roadmap_import_skus(jsonb, text)         to authenticated;
grant execute on function public.roadmap_categories()                     to authenticated;
grant execute on function public.roadmap_approvers()                      to authenticated;
