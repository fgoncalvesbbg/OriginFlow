-- 167: Roadmap Creator — the reference/annotation split, and the guarantee that protects it.
--
-- WHAT THIS MODULE IS. Pivot the product catalogue into a per-category roadmap grid, mark what
-- is being replaced or retired, plan the gaps with placeholder cards, and present it — with the
-- economics hidden — to a supplier in the room. Ported from ProductToolkit's `apps/roadmap`
-- (SQL Server + Express); see docs/originflow-roadmap-creator-module.md for every decision, and
-- docs/originflow-port-three-modules.md §1 (lines 140-386) for the full feature/UI spec.
--
-- THE MODEL — TWO HALVES THAT MUST NEVER DAMAGE EACH OTHER.
--
--   REFERENCE (written only by an import)     ANNOTATIONS (written only by a person)
--     roadmap_import   one row per upload       roadmap_item_flag   per-SKU mark + comment
--     roadmap_sku      one row per SKU          roadmap_placer      one placeholder in one cell
--                                               roadmap_axis_value  hand-added family/row/column
--                                               roadmap_audit       append-only
--
-- THE LOAD-BEARING GUARANTEE. A refreshed export can insert and update reference rows but can
-- NEVER delete one, and never touches an annotation table at all. A SKU that drops out of a
-- newer export is marked is_current = false ("not in latest file") and still renders, dimmed,
-- so the EOL note somebody wrote against it is not silently lost. If it reappears in a later
-- file it flips back to true with its flag and comment still attached.
--
-- THREE THINGS HOLD THAT UP, AND ALL THREE ARE DELIBERATE:
--
--  1. `roadmap_import_skus()` below is an INSERT .. ON CONFLICT DO UPDATE. It has no delete
--     branch and cannot be given one by accident — this is strictly stronger than the source's
--     T-SQL MERGE, which relied on a missing `WHEN NOT MATCHED BY SOURCE` clause.
--  2. THERE ARE NO FOREIGN KEYS IN THIS SCHEMA. Not an omission. `roadmap_item_flag.sku` does
--     not reference `roadmap_sku.sku`, and `roadmap_sku.last_import_id` does not reference
--     `roadmap_import`. A flag MUST be able to outlive the SKU vanishing from an export —
--     adding the "obvious missing" FK would delete exactly the annotations this module exists
--     to protect. Referential integrity here is a bug, not a feature.
--  3. The import raises on an empty payload. Without that guard a failed browser-side parse
--     posts zero rows and the delist pass marks the entire catalogue not-current.
--
-- WHY THE IMPORT IS A FUNCTION AND NOT CLIENT WRITES. src/data/ports/database.port.ts has no
-- transaction primitive, and the upsert and the delist pass must be atomic or a mid-flight
-- failure delists everything. So the whole import is one SECURITY DEFINER function invoked
-- through db.rpc() — the escape hatch src/data/PORTING.md already documents for this case.
-- That also let the source's `roadmap_sku_stage` table disappear: jsonb_to_recordset replaces
-- it, which removes a TRUNCATE (needs table-owner rights on Supabase) and the bulk-load driver.
-- Six tables here, seven in the source.
--
-- WHAT WAS DROPPED FROM THE SOURCE SCHEMA. `roadmap_item_flag.approved` and
-- `roadmap_placer.approved` (BIT) — both superseded by `status` and documented as unused in
-- schema.sql:158-163. The source kept them because that file is additive-only on deployed
-- instances; this is a first creation, so they simply do not exist.
--
-- WHAT WAS ADDED. CHECK constraints on the enum-ish columns. The source validated these only
-- in routes.js, which meant a direct SQL write could store 'REPLACE' or 'Pending' and the board
-- would silently fail to match it. The value sets are closed and live in
-- src/pages/roadmap/roadmap.constants.ts — keep the two in step.

-- ── Reference data ───────────────────────────────────────────────────────────

