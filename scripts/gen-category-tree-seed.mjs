// Generates db_migrations/133_category_tree_l1_l2.sql from docs/tree.csv.
// Re-runnable: the emitted SQL is idempotent, so regenerating and re-applying is safe.
import { readFileSync, writeFileSync } from 'node:fs';

const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";

// Two misspellings in the source CSV. Fixed here rather than seeded into the tree;
// drop an entry to keep the CSV spelling instead.
const TYPO_FIXES = {
  'Elelctric Radiators': 'Electric Radiators',
  'Ceilling Hoods': 'Ceiling Hoods',
};

// Existing categories_l3 rows that do not match a CSV leaf by name, mapped by hand.
// `to` is the canonical CSV leaf the row is renamed to and filed under.
const FUZZY = {
  'd75a7122-a9d8-478c-b9d4-2a44188353b0': { was: 'Designer Infrared Panels', to: 'Infrared Panels' },
  'f1df6682-f7ec-4884-8867-3c2534a15809': { was: 'VTC Hobs', to: 'Glass-Ceramic Hobs' },
  '9ffbaa75-ee7b-4b5d-acdf-c1d712196aa7': { was: 'Solar Fountains', to: 'Fountains' },
  '8d9090c0-05eb-4798-a4e1-95392a04a72c': { was: 'Coffee Machines', to: 'Automatic Coffee Machines' },
  '2042b131-f838-46ba-980f-9e4efa5f6df2': { was: 'Dehumidifiers', to: 'Home Dehumidifiers' },
  '03c60698-a048-425d-8a45-45e1d2570a2d': { was: 'Wine Fridges', to: 'Freestanding Wine Coolers' },
};

// Rows with no place in the tree: kept, deactivated, left unparented.
const RETIRE = [
  ['c6d8d538-b51d-4309-9fae-4f6bea2e5584', 'Hobs - Test'],
  ['a93170ed-84f3-4224-a8e4-9c64af86cf70', 'Hoods - Test'],
  ['8d0d1798-782a-4501-bcbd-6fd1c0b3029a', 'Chimney Hoods (empty duplicate)'],
];

const csv = readFileSync('docs/tree.csv', 'utf8').replace(/^﻿/, '');
const rows = csv.split(/\r?\n/).slice(1)
  .map((l) => l.split(',').map((s) => s.trim()))
  .filter((r) => r[0]);

// Build the tree. A CSV row with an empty L3 is an L2 leaf: mirror it as an L3 of the
// same name so every category stays addressable at L3 (all six FK tables point there).
const tree = new Map(); // l1 -> Map(l2 -> [l3...])
for (const [l1, l2, l3raw] of rows) {
  if (!tree.has(l1)) tree.set(l1, new Map());
  const l2s = tree.get(l1);
  if (!l2s.has(l2)) l2s.set(l2, []);
  const leaf = l3raw || l2; // mirror the L2 name when there is no L3
  const name = TYPO_FIXES[leaf] ?? leaf;
  if (!l2s.get(l2).includes(name)) l2s.get(l2).push(name);
}

const out = [];
const p = (s = '') => out.push(s);

p('-- Migration 133: three-level category tree (L1 > L2 > L3)');
p('--');
p('-- Generated by scripts/gen-category-tree-seed.mjs from docs/tree.csv. Do not hand-edit;');
p('-- change the CSV or the mapping tables in that script and regenerate.');
p('--');
p('-- Additive and idempotent. categories_l3 keeps its primary key and every row, so the six');
p('-- tables that reference it (projects, rfqs, compliance_requests, compliance_requirements,');
p('-- product_features, supplier_proposals) and category_attributes are untouched.');
p('');
p('BEGIN;');
p('');
p('-- 1. Parent levels ---------------------------------------------------------');
p('');
p('CREATE TABLE IF NOT EXISTS public.categories_l1 (');
p('  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),');
p('  name       text NOT NULL UNIQUE,');
p('  sort_order integer NOT NULL DEFAULT 0,');
p('  active     boolean NOT NULL DEFAULT true,');
p('  created_at timestamptz NOT NULL DEFAULT now()');
p(');');
p('');
p('CREATE TABLE IF NOT EXISTS public.categories_l2 (');
p('  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),');
p('  l1_id      uuid NOT NULL REFERENCES public.categories_l1(id) ON DELETE RESTRICT,');
p('  name       text NOT NULL,');
p('  sort_order integer NOT NULL DEFAULT 0,');
p('  active     boolean NOT NULL DEFAULT true,');
p('  created_at timestamptz NOT NULL DEFAULT now(),');
p('  UNIQUE (l1_id, name)');
p(');');
p('');
p('CREATE INDEX IF NOT EXISTS idx_categories_l2_l1_id ON public.categories_l2(l1_id);');
p('');
p('-- 2. Hang the existing leaf table off L2 -----------------------------------');
p('-- Nullable on purpose: a leaf with no parent is the "Uncategorised" bucket, which is');
p('-- where unmatched legacy rows land rather than being deleted.');
p('');
p('ALTER TABLE public.categories_l3');
p('  ADD COLUMN IF NOT EXISTS l2_id uuid REFERENCES public.categories_l2(id) ON DELETE RESTRICT,');
p('  ADD COLUMN IF NOT EXISTS sort_order integer NOT NULL DEFAULT 0;');
p('');
p('CREATE INDEX IF NOT EXISTS idx_categories_l3_l2_id ON public.categories_l3(l2_id);');
p('');
p('COMMENT ON COLUMN public.categories_l3.l2_id IS');
p("  'Parent L2. NULL means uncategorised - the row is kept and usable but sits outside the tree.';");
p('');
p('-- 3. RLS - mirror categories_l3 exactly ------------------------------------');
p('');
p('ALTER TABLE public.categories_l1 ENABLE ROW LEVEL SECURITY;');
p('ALTER TABLE public.categories_l2 ENABLE ROW LEVEL SECURITY;');
p('');
for (const t of ['categories_l1', 'categories_l2']) {
  p('DROP POLICY IF EXISTS "Enable all for ' + t + '" ON public.' + t + ';');
  p('CREATE POLICY "Enable all for ' + t + '" ON public.' + t);
  p("  FOR ALL USING (auth.role() = 'authenticated');");
  p('');
  p('DROP POLICY IF EXISTS "Allow public read access to ' + t + '" ON public.' + t + ';');
  p('CREATE POLICY "Allow public read access to ' + t + '" ON public.' + t);
  p('  FOR SELECT USING (true);');
  p('');
}

p('-- 4. Seed L1 ----------------------------------------------------------------');
p('');
const l1Names = [...tree.keys()];
p('INSERT INTO public.categories_l1 (name, sort_order) VALUES');
p(l1Names.map((n, i) => '  (' + q(n) + ', ' + (i + 1) * 10 + ')').join(',\n'));
p('ON CONFLICT (name) DO NOTHING;');
p('');

p('-- 5. Seed L2 ----------------------------------------------------------------');
p('');
const l2Vals = [];
for (const [l1, l2s] of tree) {
  let i = 0;
  for (const l2 of l2s.keys()) {
    i += 1;
    l2Vals.push('  (' + q(l1) + ', ' + q(l2) + ', ' + i * 10 + ')');
  }
}
p('INSERT INTO public.categories_l2 (l1_id, name, sort_order)');
p('SELECT l1.id, v.l2_name, v.sort_order');
p('FROM (VALUES');
p(l2Vals.join(',\n'));
p(') AS v(l1_name, l2_name, sort_order)');
p('JOIN public.categories_l1 l1 ON l1.name = v.l1_name');
p('ON CONFLICT (l1_id, name) DO NOTHING;');
p('');

p('-- 6. Rename the hand-mapped legacy rows to their canonical CSV leaf ---------');
p('-- Ids are preserved, so all attributes, projects and requirements ride along.');
p('');
for (const [id, m] of Object.entries(FUZZY)) {
  p('UPDATE public.categories_l3 SET name = ' + q(m.to));
  p('  WHERE id = ' + q(id) + ' AND name = ' + q(m.was) + ';  -- ' + m.was + ' -> ' + m.to);
}
p('');

p('-- 7. Seed / file L3 ---------------------------------------------------------');
p('-- Match by name against the leaves that already exist: an existing row is filed under');
p('-- its L2, a missing one is inserted. Never deletes.');
p('');
const l3Vals = [];
for (const [l1, l2s] of tree) {
  for (const [l2, leaves] of l2s) {
    leaves.forEach((leaf, i) => {
      l3Vals.push('  (' + q(l1) + ', ' + q(l2) + ', ' + q(leaf) + ', ' + (i + 1) * 10 + ')');
    });
  }
}
p('CREATE TEMP TABLE _tree_l3 (l1_name text, l2_name text, l3_name text, sort_order integer) ON COMMIT DROP;');
p('');
p('INSERT INTO _tree_l3 (l1_name, l2_name, l3_name, sort_order) VALUES');
p(l3Vals.join(',\n') + ';');
p('');
p('-- Rows with no place in the tree. Declared up front so the filing step below skips them:');
p('-- the empty duplicate "Chimney Hoods" shares a name with a real leaf and would otherwise');
p('-- be filed alongside it.');
p('CREATE TEMP TABLE _retired_l3 (id uuid, note text) ON COMMIT DROP;');
p('INSERT INTO _retired_l3 (id, note) VALUES');
p(RETIRE.map(([id, label]) => '  (' + q(id) + ', ' + q(label) + ')').join(',\n') + ';');
p('');
p('-- 7a. File existing leaves under their L2 (id, attributes and FKs preserved).');
p('--     Only ever fills a NULL parent, so a hand-placed row is never overwritten.');
p('UPDATE public.categories_l3 c');
p('SET l2_id = l2.id, sort_order = t.sort_order');
p('FROM _tree_l3 t');
p('JOIN public.categories_l1 l1 ON l1.name = t.l1_name');
p('JOIN public.categories_l2 l2 ON l2.l1_id = l1.id AND l2.name = t.l2_name');
p('WHERE c.name = t.l3_name');
p('  AND c.l2_id IS NULL');
p('  AND c.id NOT IN (SELECT id FROM _retired_l3);');
p('');
p('-- 7b. Insert the leaves that do not exist yet. A retired row does not count as an');
p('--     existing leaf, so the real "Chimney Hoods" is still seeded if only the dup remains.');
p('INSERT INTO public.categories_l3 (name, l2_id, sort_order, active, is_finalized)');
p('SELECT t.l3_name, l2.id, t.sort_order, true, false');
p('FROM _tree_l3 t');
p('JOIN public.categories_l1 l1 ON l1.name = t.l1_name');
p('JOIN public.categories_l2 l2 ON l2.l1_id = l1.id AND l2.name = t.l2_name');
p('WHERE NOT EXISTS (');
p('  SELECT 1 FROM public.categories_l3 c');
p('  WHERE c.name = t.l3_name AND c.id NOT IN (SELECT id FROM _retired_l3)');
p(');');
p('');

p('-- 8. Retire the rows with no place in the tree ------------------------------');
p('-- Kept, not deleted: deactivated and unparented so they show as Uncategorised and stay');
p('-- out of the pickers. Reversible with a single UPDATE.');
p('');
p('UPDATE public.categories_l3 c');
p('SET active = false, l2_id = NULL');
p('FROM _retired_l3 r');
p('WHERE c.id = r.id;');
p('');
p("NOTIFY pgrst, 'reload schema';");
p('');
p('COMMIT;');
p('');

writeFileSync('db_migrations/133_category_tree_l1_l2.sql', out.join('\n'));
console.log('L1=' + l1Names.length + ' L2=' + l2Vals.length + ' L3=' + l3Vals.length);
